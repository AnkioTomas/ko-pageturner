月读拓展登记：让月读把「翻页器」认成自己的扩展。

插件根目录放 `moon_source.lua` 即被月读 source.registry 登记为扩展（id 必须形如 `ext.<name>`）。
这里**只声明身份**（`source = false`：不做书源），不声明任何能力位 —— 首页组件也不做。

翻页器的入口都是月读 / KOReader 已经有的，这里不重复：
  - **月读底栏「拓展」**：月读把第三方插件的主菜单项收进去（设置 → 桌面 → 底栏拓展，默认关，
    要打开），里面就是「翻页器」的菜单：状态、重新接管、几个开关。
  - **KOReader 菜单**：齿轮 → 网络 → 翻页器。
  - **启停守护进程**：归月读自己的蓝牙开关（顶栏蓝牙项 / 桌面快捷面板）。

留着这个文件的意义：翻页器在月读里有正式的扩展 id（占住 `ext.pageturner`，别家扩展不能重名），
以后想往首页加东西也有地方加。**删掉它不影响翻页器的任何功能**，只少了这个 id。

@module pageturner.moon_source
--]]

return {
    api = 1,
    id = "ext.pageturner",
    provides = { source = false },
}
